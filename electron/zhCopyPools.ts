/** 中文账号专用：人工挑选的网名 / 评论。禁止组合模板（北巷路过叔、月台上的水果）。禁数字。 */

function uniqueNoDigit(list: string[], maxLen = 22): string[] {
  const seen = new Set<string>()
  const out: string[] = []
  for (const raw of list) {
    const t = raw.replace(/\s+/g, ' ').trim()
    if (!t || /\d/.test(t) || t.length > maxLen || t.length < 2) continue
    const n = t.toLowerCase().replace(/\s+/g, '')
    if (seen.has(n)) continue
    seen.add(n)
    out.push(t)
  }
  return out
}

